def write_csv(path: Path, rows: list[dict[str, object]], fields: list[str]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def load_evidence_ids() -> set[str]:
    with (DATA_DIR / "evidence_ledger.csv").open(newline="", encoding="utf-8") as handle:
        return {row["evidence_id"] for row in csv.DictReader(handle)}


def split_ids(value: str) -> list[str]:
    if not value:
        return []
    return [item.strip() for item in value.split(";") if item.strip()]


def validate_targets(evidence_ids: set[str]) -> None:
    seen: set[str] = set()
    for row in CALIBRATION_TARGETS:
        target_id = row["target_id"]
        if target_id in seen:
            raise ValueError(f"Duplicate target_id: {target_id}")
        seen.add(target_id)
        missing = [eid for eid in split_ids(str(row["evidence_ids"])) if eid not in evidence_ids]
        if missing:
            raise ValueError(f"Unknown evidence_ids for {target_id}: {missing}")


def validate_priors(evidence_ids: set[str]) -> None:
    seen: set[str] = set()
    groups = {row["parameter_group"] for row in PARAMETER_PRIORS}
    if groups != REQUIRED_PARAMETER_GROUPS:
        missing_groups = REQUIRED_PARAMETER_GROUPS - groups
        extra_groups = groups - REQUIRED_PARAMETER_GROUPS
        raise ValueError(f"Parameter groups mismatch. Missing={missing_groups}, extra={extra_groups}")

    for row in PARAMETER_PRIORS:
        parameter_id = row["parameter_id"]
        if parameter_id in seen:
            raise ValueError(f"Duplicate parameter_id: {parameter_id}")
        seen.add(parameter_id)

        strategy = str(row["source_strategy"])
        if strategy not in ALLOWED_SOURCE_STRATEGIES:
            raise ValueError(f"Invalid source_strategy for {parameter_id}: {strategy}")

        missing = [eid for eid in split_ids(str(row["evidence_ids"])) if eid not in evidence_ids]
        if missing:
            raise ValueError(f"Unknown evidence_ids for {parameter_id}: {missing}")

        if not row["evidence_ids"] and strategy == "direct_pedder":
            raise ValueError(f"{parameter_id} cannot be direct_pedder without evidence_ids")


def main() -> None:
    evidence_ids = load_evidence_ids()
    validate_targets(evidence_ids)
    validate_priors(evidence_ids)
    write_csv(DATA_DIR / "calibration_targets.csv", CALIBRATION_TARGETS, TARGET_FIELDS)
    write_csv(DATA_DIR / "parameter_priors.csv", PARAMETER_PRIORS, PRIOR_FIELDS)
    print(
        f"Wrote {len(CALIBRATION_TARGETS)} calibration targets and {len(PARAMETER_PRIORS)} parameter priors."
    )


if __name__ == "__main__":
    main()

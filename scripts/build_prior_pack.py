def split_ids(value: str) -> list[str]:
    if not value:
        return []
    return [item.strip() for item in value.split(";") if item.strip()]


def load_evidence_ids() -> set[str]:
    with (DATA_DIR / "evidence_ledger.csv").open(newline="", encoding="utf-8") as handle:
        return {row["evidence_id"] for row in csv.DictReader(handle)}


def write_csv(path: Path, rows: list[dict[str, object]], fields: list[str]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def build_family_rows() -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    parameter_ids = [row["parameter_id"] for row in PARAMETER_PRIORS]
    for family in FAMILIES:
        fixed_zero = family["fixed_zero"]
        fixed_one = family["fixed_one"]
        fixed_values = family["fixed_values"]
        unused = family["unused"]
        for parameter_id in parameter_ids:
            if parameter_id in fixed_values:
                status = "fixed_value"
                fixed_value = fixed_values[parameter_id]
                notes = "Fixed at a family-specific value."
            elif parameter_id in fixed_zero:
                status = "fixed_zero"
                fixed_value = 0
                notes = "Disabled in this hypothesis family."
            elif parameter_id in fixed_one:
                status = "fixed_one"
                fixed_value = 1
                notes = "Neutralized at one in this hypothesis family."
            elif parameter_id in unused:
                status = "unused"
                fixed_value = ""
                notes = "State or process omitted from this hypothesis family."
            else:
                status = "estimate"
                fixed_value = ""
                notes = "Estimated from the prior pack for this hypothesis family."

            rows.append(
                {
                    "family_id": family["family_id"],
                    "family_label": family["family_label"],
                    "parameter_id": parameter_id,
                    "parameter_status": status,
                    "fixed_value": fixed_value,
                    "notes": notes,
                }
            )
    return rows


def validate_priors(evidence_ids: set[str]) -> None:
    seen: set[str] = set()
    groups = {row["parameter_group"] for row in PARAMETER_PRIORS}
    if groups != REQUIRED_PARAMETER_GROUPS:
        missing_groups = REQUIRED_PARAMETER_GROUPS - groups
        extra_groups = groups - REQUIRED_PARAMETER_GROUPS
        raise ValueError(f"Parameter groups mismatch. Missing={missing_groups}, extra={extra_groups}")

    for row in PARAMETER_PRIORS:
        parameter_id = str(row["parameter_id"])
        if parameter_id in seen:
            raise ValueError(f"Duplicate parameter_id: {parameter_id}")
        seen.add(parameter_id)

        strategy = str(row["source_strategy"])
        if strategy not in ALLOWED_SOURCE_STRATEGIES:
            raise ValueError(f"Invalid source_strategy for {parameter_id}: {strategy}")

        transform = str(row["sampling_transform"])
        if transform not in ALLOWED_SAMPLING_TRANSFORMS:
            raise ValueError(f"Invalid sampling_transform for {parameter_id}: {transform}")

        missing = [eid for eid in split_ids(str(row["evidence_ids"])) if eid not in evidence_ids]
        if missing:
            raise ValueError(f"Unknown evidence_ids for {parameter_id}: {missing}")

        if not row["evidence_ids"] and strategy == "direct_pedder":
            raise ValueError(f"{parameter_id} cannot be direct_pedder without evidence_ids")


def main() -> None:
    evidence_ids = load_evidence_ids()
    validate_priors(evidence_ids)
    family_rows = build_family_rows()
    write_csv(DATA_DIR / "parameter_priors.csv", PARAMETER_PRIORS, PRIOR_FIELDS)
    write_csv(DATA_DIR / "model_family_parameter_map.csv", family_rows, FAMILY_FIELDS)
    write_csv(DATA_DIR / "parameter_constraints.csv", PARAMETER_CONSTRAINTS, CONSTRAINT_FIELDS)
    print(
        "Wrote "
        f"{len(PARAMETER_PRIORS)} parameter priors, "
        f"{len(family_rows)} family-map rows, and "
        f"{len(PARAMETER_CONSTRAINTS)} parameter constraints."
    )


if __name__ == "__main__":
    main()
